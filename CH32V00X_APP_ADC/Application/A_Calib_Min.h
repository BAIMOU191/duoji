#ifndef __A_CALIB_MIN_H__
#define __A_CALIB_MIN_H__

#include <stdint.h>

/*
 * A_Calib_Min.h —— 唯一的自动标定程序
 *
 * 输出4个单台参数(速度斜率、动摩擦、起转PWM、装配方向)和3个型号级参数
 * (机械时间常数、纯延迟、主动制动比)，其余量全部由 A_Parameter.h 自动派生：
 * v_ss / a0 / Ka / 观测器增益都能由它们解析算出，分别测量只会让各自的测量
 * 噪声互相矛盾。推导与实测校验见 A_Calib_Min.c 的文件头。
 *
 * 使用：main.c 里定义 APP_MODE_CALIB，上电1秒后自动开始，结束后串口打印
 * 若干行 #define，直接替换 A_Parameter.h 中的标定参数。
 *
 * 【开跑前必须满足】输出轴要能自由转动(拆掉舵盘/负载)，**并且当前位置读得出
 * 角度**——上电时读不到会直接 fail=3 中止，标定不做脱困，先手动把轴拨回可测
 * 范围。有限行程的传感器(电位器)全程会自动预定位到起跑点，行程两端各留5度
 * 保护带，越界立即断电中止(fail=4)；整圈可测的传感器不受这两条限制。
 *
 * 中止码：1=满PWM也不动，2=方向测不出，3=编码器读不到，4=冲出安全行程，
 *         5=预定位超时。
 *
 * 传感器分辨率直接决定几项测试的裕度：电位器比磁编码器粗约3.6倍
 * (7.94 vs 2.20 厘度/LSB)，T3纯延迟、T6最小位移、T8振铃三项的裕度都被吃掉，
 * 重复跑几次看散布再决定信不信。
 */

void A_Calib_Min_Init(void);       /* 初始化标定状态机 */
void A_Calib_Min_Tasks_Init(void); /* 只注册标定拍与喂狗任务 */

#endif /* __A_CALIB_MIN_H__ */
