#ifndef __C_SPEED_OBSERVER_H__
#define __C_SPEED_OBSERVER_H__

#include <stdint.h>
#include "A_Parameter.h"

/*
 * C_Speed_Observer.h —— 3状态模型观测器(位置/速度/负载扰动)
 *
 * ============================ 为什么换掉SG微分器 ============================
 * 旧版位置走alpha-beta、速度走7点SG微分器，两者都只用编码器一个信息源。
 * 实测标定给出的硬约束：
 *     MT6701 14位，1计数=2.197厘度，运动中噪声 sigma=0.76厘度
 *     静止时**完全没有dither**(2000拍原始计数一动不动)
 * 没有dither意味着过采样平均无法恢复亚LSB分辨率——平均100次还是同一个数。
 * 于是编码器单源的速度噪声被死死钉在这条曲线上(N点中心差分)：
 *     N=5:235   N=7:143   N=11:72   N=15:45  厘度/秒,  滞后=(N-1)/2 拍
 * 想降噪只能加长窗口，而加长窗口就是加滞后，无解。实测SG-11在暂态反而
 * 比SG-7更差(梯形269 vs 190，换向560 vs 378)：省下的噪声被滞后吃光还倒亏。
 *
 * 出路是加入**第二个信息源**：本模块下发的PWM，以及标定出来的电机模型。
 * 这个信息零延迟、零噪声(是算出来的不是测出来的)。让模型负责高频段、
 * 编码器负责低频真值，就同时拿到低噪声和很小的相位滞后。本模块准确名称是
 * “带常值扰动状态的Luenberger观测器/线性ESO”，不是经典Q滤波逆模型干扰观测器。
 * 两者目标相同，但本实现不需要求对象逆，定点代码更少。对比(厘度/秒)：
 *     工况        SG-7   SG-11   本模块(25Hz)
 *     爬行11deg/s  115     60      34
 *     匀速99deg/s   59     43      43
 *     梯形         190    269      37
 *     往复换向     378    560      62
 *
 * ============================ 模型与状态 ============================
 * 一阶电机模型，独立常数由A_Calib_Min实测或型号金样给出：
 *     dv/dt = ( Kv*(u - d) - v ) / tau        Kv=plant_kvff的倒数, tau=plant_tau_ms
 *     dp/dt = v
 * 状态 x = [位置, 速度, 负载扰动d]，d 的单位是等效PWM计数。
 * 每拍先按模型预测，再用编码器残差按固定增益修正(稳态卡尔曼形式)：
 *     e = 测量位置 - 预测位置
 *     位置 += L1*e ; 速度 += L2*e ; d += L3*e   (L3设计值为负)
 *
 * d状态吸收低频负载和等效输入偏差，是本结构的鲁棒性来源；它不能消除高频
 * 未建模共振或过大的时间常数误差。主机测试覆盖对象增益与tau各±30%。
 *
 * ============================ 三个必须做对的实现点 ============================
 * 1) **输入要按纯延迟对齐**。标定实测指令到编码器响应有3拍纯延迟，
 *    预测步必须喂 u[k-dead] 而不是 u[k]。实测梯形工况RMS 80 -> 37，
 *    一个环形缓冲换来2倍精度。
 *    输入还必须与状态统一为“编码器角度增大为正”：控制器返回的是H桥物理
 *    PWM，所以观测器入口乘一次CAL_MOTOR_SIGN还原算法坐标。
 *
 * 2) **输入要减掉库仑摩擦**。摩擦随运动方向翻符号，若不减，每次换向
 *    d 状态都要重新收敛，换向工况会从62劣化到200以上。本模块内部按
 *    速度估计的符号自行扣除，不依赖控制器。
 *
 * 3) **d 状态只在观测器内部用，不要前馈到PWM**。它按25Hz估计带宽整定，
 *    直接喂执行器会把观测器噪声灌进去：实测小位移保持时的位置摆动
 *    从0.00劣化到3.04厘度。负载补偿交给控制器的速度环积分。
 *
 * ============================ 增益怎么重算 ============================
 * obs_l1/l2/l3 是对 (tau, Kv) 做三重极点配置的结果，换舵机后必须跟着
 * 对象常数一起重算。离散模型(T=1ms)：
 *     A = [[1, T, 0], [0, 1-T/tau, -T*Kv/tau], [0, 0, 1]]
 *     Cbar = [1,0,0] * A = [1, T, 0]
 * 令 (A - L*Cbar) 的三个特征值都等于 exp(-2*pi*f*T)，f 取25Hz。
 * 这一步在电脑上做一次，板子上全程不需要浮点也不需要矩阵运算。
 * 带宽取舍：15Hz稳态更干净但换向差，40Hz反之，25Hz最均衡。
 *
 * ============================ 定点约定 ============================
 * 位置/速度/负载状态都用Q8。位置与输出同为厘度，速度对外为厘度/秒。
 * 每拍只有乘法和移位，无除法(除以tau和采样率都预先换算成Q16/Q22倒数)。
 *
 * 电机连续转动跨0点时残差会被折回一个编码器周期内，不产生假尖峰。
 * 前提是每拍实际转动量远小于半圈——1kHz下恒满足。
 *
 * 本模块按单实例设计，状态封装在.c内部。
 */

/* 观测器输出 */
typedef struct {
    int32_t pos;  /* 滤波后位置，厘度 */
    int32_t vel;  /* 速度估计，厘度/秒，无滞后 */
    int32_t load; /* 负载扰动估计，等效PWM计数。仅供调试观察，
                   * **不要**拿去做前馈，理由见上文第3点。 */
} SpeedObsOut_t;

/*
 * 初始化观测器。
 * @param init_pos 初始位置(厘度)，一般用上电时的编码器角度
 */
void C_SpeedObs_Init(int32_t init_pos);

/*
 * 固定周期(1ms)调用一次。
 * @param measured_pos 本拍编码器角度(厘度)
 * @param pwm_applied  **上一拍实际施加**的PWM(限幅后的值)，观测器内部
 *                     再按纯延迟对齐，调用方不需要自己延迟
 * @param out          输出：位置/速度/负载估计
 */
void C_SpeedObs_Update(int32_t measured_pos, int16_t pwm_applied, SpeedObsOut_t *out);

#endif /* __C_SPEED_OBSERVER_H__ */
