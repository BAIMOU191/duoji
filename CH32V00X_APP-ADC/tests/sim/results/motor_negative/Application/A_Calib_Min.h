#ifndef __A_CALIB_MIN_H__
#define __A_CALIB_MIN_H__

#include <stdint.h>

/*
 * A_Calib_Min.h —— 唯一的自动标定程序(电位器版)
 *
 * 工程只保留这一份标定代码。它输出3个单台参数(速度斜率、摩擦、方向)和
 * 3个型号级参数(时间常数、纯延迟、主动制动比)；其余量全部自动派生。
 *
 * 为什么只要这些：v_ss/a0/Ka/观测器增益都能由它们解析算出，
 * 推导与实测校验见 A_Calib_Min.c 文件头和 A_Config.c 的派生层。
 *
 * 使用：main.c 里定义 APP_MODE_CALIB，上电1秒后自动开始。结束后串口打印
 * 若干行 #define，直接替换 A_Parameter.h 中的标定参数。
 *
 * 【开跑前必须满足】输出轴要能自由转动，**并且抽头必须落在电位器碳膜上**
 * (角度读得出来)。上电时若在死区里会直接 fail=3 中止——标定不做脱困，先手动
 * 把轴拨回可测范围。全程会自动回到行程正中再施加激励，行程两端各留 5 度
 * 保护带，越界立即断电中止(fail=4)。
 *
 * 电位器分辨率比磁编码器粗 3.6 倍(7.94 厘度/LSB)，T3 纯延迟、T6 最小位移、
 * T8 振铃三项的裕度都被吃掉，重复跑几次看散布再决定信不信。
 */

void A_Calib_Min_Init(void);        /* 初始化标定状态机 */
void A_Calib_Min_Tasks_Init(void);  /* 注册标定专用任务表(替代A_Tasks_Init) */

#endif /* __A_CALIB_MIN_H__ */
