#ifndef __C_SPEED_OBSERVER_H__
#define __C_SPEED_OBSERVER_H__

#include <stdint.h>
#include "A_Parameter.h"

/*
 * C_Speed_Observer.h —— 3状态模型观测器(位置/速度/负载扰动)
 *
 * ============================ 为什么是模型观测器 ============================
 * 单靠编码器求速度(N点中心差分/SG微分器)有一条绕不过去的曲线：噪声正比于
 * 1/N、滞后正比于 (N-1)/2 拍。想降噪只能加窗，加窗就是加滞后，在暂态上
 * 得不偿失(旧版实测 SG-11 在梯形/换向工况反而比 SG-7 差)。
 *
 * 出路是加入**第二个信息源**：本模块下发的 PWM 加上标定出来的电机模型。
 * 这个信息零延迟、零噪声(是算出来的不是测出来的)。模型负责高频段、编码器
 * 负责低频真值，于是同时拿到低噪声和很小的相位滞后。
 *
 * 准确名称是"带常值扰动状态的 Luenberger 观测器/线性 ESO"，不是经典 Q 滤波
 * 逆模型干扰观测器；两者目标相同，但本实现不需要求对象逆，定点代码更少。
 *
 * ============================ 模型与状态 ============================
 * 一阶电机模型，常数全部来自 A_Parameter.h 的标定输入：
 *     dv/dt = ( Kv*(u - d) - v ) / tau
 *     dp/dt = v
 * 其中 Kv = 65536/PLANT_SPEED_SLOPE_Q16 (厘度/秒 每PWM计数)，
 *     tau = PLANT_TAU_MS。
 * 状态 x = [位置, 速度, 负载扰动d]，d 的单位是等效 PWM 计数。
 * 每拍先按模型预测，再用编码器残差按固定增益修正(稳态卡尔曼形式)：
 *     e = 测量位置 - 预测位置
 *     位置 += L1*e ; 速度 += L2*e ; d += L3*e   (L3 设计值为负)
 *
 * d 状态吸收低频负载和等效输入偏差，是本结构的鲁棒性来源；它不能消除高频
 * 未建模共振或过大的时间常数误差。主机测试覆盖对象增益与 tau 各 ±30%。
 *
 * ============================ 三个必须做对的实现点 ============================
 * 1) **输入要按纯延迟对齐**。指令到编码器响应有 PLANT_DEAD_TICKS 拍纯延迟，
 *    预测步必须喂 u[k-dead] 而不是 u[k]，否则模型在加减速段系统性超前。
 *    输入还必须与状态统一为"编码器角度增大为正"：控制器返回的是 H 桥物理
 *    PWM，所以观测器入口乘一次 CAL_MOTOR_SIGN 还原算法坐标。
 *
 * 2) **输入要减掉库仑摩擦**。摩擦随运动方向翻符号，不减的话每次换向 d 状态
 *    都要重新收敛。本模块按速度估计的符号自行扣除，不依赖控制器；零速附近
 *    用连续过渡而不是硬切换，避免制造一个 ±CAL_FRICTION_PWM 的人为阶跃。
 *
 * 3) **d 状态只在观测器内部用，绝不前馈到 PWM**。它按观测器带宽整定，直接
 *    喂执行器等于把观测器噪声灌进输出。负载补偿是速度环积分的职责，全系统
 *    只允许有那一个积分器(见 C_Pos_Ctrl.c 第10节)。
 *
 * ============================ 增益从哪来 ============================
 * OBS_L1_Q15 / OBS_L2_Q15 / OBS_L3_Q15 **不是手填的常数**，而是 A_Parameter.h
 * 用 OBSG_* 那串宏在编译期算出来的：对 (tau, Kv) 做三重极点配置，令
 *     A    = [[1, T, 0], [0, 1-T/tau, -T*Kv/tau], [0, 0, 1]]
 *     Cbar = [1,0,0] * A = [1, T, 0]
 * 的 (A - L*Cbar) 三个特征值都等于 exp(-2*pi*f*T)，T=1ms，f=TUNE_OBS_BW_HZ。
 * 所以换舵机只需要改标定输入，增益自动跟着走，板子上全程不需要浮点。
 *
 * 带宽 f 由**传感器噪声**决定而不是由稳定性决定，取值理由见 A_Parameter.h
 * 中 TUNE_OBS_BW_HZ 那一段(电位器滑动接触噪声 91% 的能量在 50Hz 以上，
 * 而对象转折频率只有 3Hz)。
 *
 * ============================ 定点约定 ============================
 * 位置/速度/负载状态都用Q8。位置与输出同为厘度，速度对外为厘度/秒。
 * 每拍只有乘法和移位，无除法(除以tau和采样率都预先换算成Q16/Q22倒数)。
 *
 * 电机连续转动跨0点时残差会被折回一个编码器周期内，不产生假尖峰。
 * 前提是每拍实际转动量远小于半圈——1kHz下恒满足。
 *
 * 本模块按单实例设计，状态封装在.c内部。
 */

/* 观测器输出 */
typedef struct {
    int32_t pos;  /* 滤波后位置，厘度 */
    int32_t vel;  /* 速度估计，厘度/秒，无滞后 */
    int32_t load; /* 负载扰动估计，等效PWM计数。仅供调试观察，
                   * **不要**拿去做前馈，理由见上文第3点。 */
} SpeedObsOut_t;

/*
 * 初始化观测器。
 * @param init_pos 初始位置(厘度)，一般用上电时的编码器角度
 */
void C_SpeedObs_Init(int32_t init_pos);

/*
 * 固定周期(1ms)调用一次。
 * @param measured_pos 本拍编码器角度(厘度)
 * @param pwm_applied  **上一拍实际施加**的PWM(限幅后的值)，观测器内部
 *                     再按纯延迟对齐，调用方不需要自己延迟
 * @param out          输出：位置/速度/负载估计
 */
void C_SpeedObs_Update(int32_t measured_pos, int16_t pwm_applied, SpeedObsOut_t *out);

#endif /* __C_SPEED_OBSERVER_H__ */
